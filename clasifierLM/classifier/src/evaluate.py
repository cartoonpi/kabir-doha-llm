"""Step 7: evaluate every model on TEST and HUMAN, write reports/classifier_eval.md.

  python -m src.evaluate

Decision rules applied:
  keyword  -- its own rule (most hits; images = any hit). It has no real
              probabilities, so thresholds don't apply.
  logreg, fasttext -- calibrated thresholds from artifacts/thresholds.json (step 6).

The plain-English summary at the end of the report is written by a human after
reading the numbers, in reports/classifier_eval_summary.md, and included
verbatim if present (so re-running this script never overwrites it).
"""

import json
from collections import Counter

import numpy as np
from sklearn.metrics import confusion_matrix, f1_score, precision_score, recall_score

from src.baselines import KeywordModel, LogRegModel
from src.calibrate import decide
from src.common import ARTIFACTS, DATA, REPORTS, get_logger, load_tags, read_jsonl
from src.model import FastTextPredictor


def decide_for(name, pred, thresholds):
    if name == "keyword":
        tp = pred["theme_probs"]
        return {"theme": max(tp, key=tp.get), "images": [i for i, p in pred["image_probs"].items() if p > 0]}
    t = thresholds[name]
    return decide(pred, t["t_theme"], t["t_img"])


def metrics(rows, preds, decisions, image_ids):
    true = [r["theme"] for r in rows]
    pred = [d["theme"] for d in decisions]
    # top-k: correct if the final decision is right OR the true theme is among
    # the k highest probabilities (useful if the app shows k suggestions).
    def topk(k):
        return float(np.mean([d["theme"] == r["theme"] or r["theme"] in sorted(p["theme_probs"], key=p["theme_probs"].get)[-k:]
                              for r, p, d in zip(rows, preds, decisions)]))
    Y = np.array([[i in r["images"] for i in image_ids] for r in rows])
    P = np.array([[i in d["images"] for i in image_ids] for d in decisions])
    is_none_t = [t == "none" for t in true]
    is_none_p = [p == "none" for p in pred]
    return {
        "n": len(rows),
        "top1": float(np.mean([a == b for a, b in zip(true, pred)])),
        "top2": topk(2), "top3": topk(3), "top5": topk(5),
        "macroF1": f1_score(true, pred, average="macro", zero_division=0),
        # Precision for none: of the requests we called "none", how many were none?
        # Recall for none:    of the real "none" requests, how many did we catch?
        "none_P": precision_score(is_none_t, is_none_p, zero_division=0),
        "none_R": recall_score(is_none_t, is_none_p, zero_division=0),
        "img_microF1": f1_score(Y, P, average="micro", zero_division=0),
        # exact set: predicted image set == true image set (including both empty)
        "img_exact": float(np.mean([set(d["images"]) == set(r["images"]) for r, d in zip(rows, decisions)])),
    }


def fmt_tags(theme, images, probs=None):
    if probs is None:
        return f"{theme} [{', '.join(images) or '-'}]"
    t = f"{theme} ({probs['theme_probs'][theme]:.2f})"
    im = ", ".join(f"{i} ({probs['image_probs'][i]:.2f})" for i in images) or "-"
    return f"{t} [{im}]"


def main():
    log = get_logger("evaluate")
    tags = load_tags()
    theme_order = [t["id"] for t in tags["themes"]] + ["none"]
    image_ids = [i["id"] for i in tags["images"]]
    thresholds = json.loads((ARTIFACTS / "thresholds.json").read_text())
    train = read_jsonl(DATA / "splits/train.jsonl")
    sets = {"test": read_jsonl(DATA / "splits/test.jsonl"), "human": read_jsonl(DATA / "requests_human.jsonl")}
    models = {"keyword": KeywordModel(tags), "logreg": LogRegModel(tags).fit(train),
              "fasttext": FastTextPredictor(ARTIFACTS / "fasttext_best.pt")}

    results, cache = {}, {}
    for mname, model in models.items():
        for sname, rows in sets.items():
            preds = model.predict([r["text"] for r in rows])
            decs = [decide_for(mname, p, thresholds) for p in preds]
            cache[mname, sname] = (preds, decs)
            results[mname, sname] = m = metrics(rows, preds, decs, image_ids)
            log.info("%-8s %-5s n=%-4d top1 %.3f top3 %.3f top5 %.3f macroF1 %.3f | none P %.2f R %.2f | img microF1 %.3f exact %.3f",
                     mname, sname, m["n"], m["top1"], m["top3"], m["top5"], m["macroF1"], m["none_P"], m["none_R"], m["img_microF1"], m["img_exact"])

    L = ["# Classifier evaluation", "",
         "Generated by `python -m src.evaluate`. Thresholds from `artifacts/thresholds.json` "
         f"(fasttext: t_theme={thresholds['fasttext']['t_theme']}, t_img={thresholds['fasttext']['t_img']}; "
         f"logreg: t_theme={thresholds['logreg']['t_theme']}, t_img={thresholds['logreg']['t_img']}). "
         "Keyword uses its own rule.", ""]
    for sname, rows in sets.items():
        L += [f"## {sname} set (n={len(rows)})", "",
              "| model | theme top-1 | top-2 | top-3 | top-5 | theme macro-F1 | none precision | none recall | image micro-F1 | image exact-set |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for mname in models:
            m = results[mname, sname]
            L.append(f"| {mname} | {m['top1']:.3f} | {m['top2']:.3f} | {m['top3']:.3f} | {m['top5']:.3f} | {m['macroF1']:.3f} | "
                     f"{m['none_P']:.3f} | {m['none_R']:.3f} | {m['img_microF1']:.3f} | {m['img_exact']:.3f} |")
        L.append("")

    # Acceptance targets from the spec
    ft_t, ft_h, kw_h = results["fasttext", "test"], results["fasttext", "human"], results["keyword", "human"]
    checks = [
        ("fastText beats keyword on theme macro-F1 (human)", ft_h["macroF1"] > kw_h["macroF1"], f"{ft_h['macroF1']:.3f} vs {kw_h['macroF1']:.3f}"),
        ("theme top-1 >= 75% on test", ft_t["top1"] >= 0.75, f"{ft_t['top1']:.1%}"),
        ("theme top-1 >= 60% on human", ft_h["top1"] >= 0.60, f"{ft_h['top1']:.1%}"),
        ("'none' recall >= 70% (test)", ft_t["none_R"] >= 0.70, f"{ft_t['none_R']:.1%}"),
        ("'none' recall >= 70% (human)", ft_h["none_R"] >= 0.70, f"{ft_h['none_R']:.1%}"),
    ]
    L += ["## Acceptance targets (fastText-style model)", "", "| target | met? | actual |", "|---|---|---|"]
    L += [f"| {c} | {'✅' if ok else '❌'} | {v} |" for c, ok, v in checks]
    for c, ok, v in checks:
        log.info("target %-50s %s (%s)", c, "MET" if ok else "MISSED", v)

    rows = sets["test"]
    decs = cache["fasttext", "test"][1]
    true_t, pred_t = [r["theme"] for r in rows], [d["theme"] for d in decs]

    def matrix_md(labels, true, pred, title):
        """Markdown confusion table: rows = true, columns = predicted, diagonal bold."""
        cm = confusion_matrix(true, pred, labels=labels)
        out = ["", f"## {title}", "", "Rows = true, columns = predicted. The diagonal is correct.", "",
               "| true \\ pred | " + " | ".join(labels) + " |", "|---" * (len(labels) + 1) + "|"]
        for i, (t, row) in enumerate(zip(labels, cm)):
            out.append(f"| **{t}** | " + " | ".join(f"**{v}**" if i == j else (str(v) if v else "·") for j, v in enumerate(row)) + " |")
        return out

    if len(theme_order) <= 12:
        L += matrix_md(theme_order, true_t, pred_t, "Theme confusion matrix (fastText-style, test set)")
    else:
        # 101 x 101 is unreadable. Show the most-confused pairs instead...
        pairs = Counter((t, p) for t, p in zip(true_t, pred_t) if t != p)
        L += ["", "## Top 20 confused theme pairs (fastText-style, test set)", "",
              "| true | predicted as | count |", "|---|---|---|"]
        L += [f"| {t} | {p} | {n} |" for (t, p), n in pairs.most_common(20)]
        # ...and the confusion between families (~10 x 10), if tags.yaml defines them.
        fam = {t["id"]: t.get("family") for t in tags["themes"]} | {"none": "none"}
        if all(fam.values()):
            fam_order = [f["id"] for f in tags.get("families", [])] + ["none"]
            L += matrix_md(fam_order, [fam[t] for t in true_t], [fam[p] for p in pred_t],
                           "Family confusion matrix (fastText-style, test set)")
            fam_acc = np.mean([fam[t] == fam[p] for t, p in zip(true_t, pred_t)])
            L += ["", f"Family-level accuracy (right family, maybe wrong theme): {fam_acc:.3f}"]

    # Per-theme F1, worst first: where to focus data or vocabulary fixes.
    f1s = f1_score(true_t, pred_t, labels=theme_order, average=None, zero_division=0)
    support = Counter(true_t)
    L += ["", "## Per-theme F1, worst first (fastText-style, test set)", "", "| theme | F1 | test rows |", "|---|---|---|"]
    L += [f"| {t} | {f:.3f} | {support[t]} |" for t, f in sorted(zip(theme_order, f1s), key=lambda x: x[1])]

    # 15 worst errors on human: any wrong theme or image set, ranked by how
    # little probability the model gave the TRUE theme (most confidently wrong first).
    preds, decs = cache["fasttext", "human"]
    errs = [(p["theme_probs"][r["theme"]], r, p, d) for r, p, d in zip(sets["human"], preds, decs)
            if d["theme"] != r["theme"] or set(d["images"]) != set(r["images"])]
    errs.sort(key=lambda e: e[0])
    L += ["", f"## 15 worst errors, human set (fastText-style; {len(errs)} of {len(sets['human'])} requests have some error)", "",
          "Ranked by the probability given to the true theme (lowest first).", "",
          "| # | request | true | predicted | p(true theme) |", "|---|---|---|---|---|"]
    for n, (pt, r, p, d) in enumerate(errs[:15], 1):
        L.append(f"| {n} | {r['text']} | {fmt_tags(r['theme'], r['images'])} | {fmt_tags(d['theme'], d['images'], p)} | {pt:.2f} |")

    summary = REPORTS / "classifier_eval_summary.md"
    L += ["", "## Summary", ""]
    L.append(summary.read_text().strip() if summary.exists() else "_Not written yet: add reports/classifier_eval_summary.md and re-run._")

    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "classifier_eval.md").write_text("\n".join(L) + "\n")
    log.info("wrote reports/classifier_eval.md")


if __name__ == "__main__":
    main()
